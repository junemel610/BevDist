import { Platform } from 'react-native';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import * as FileSystem from 'expo-file-system/legacy';
import * as XLSX from '@redoper1/xlsx-js-style';
import { exportInvoicePdf, exportInvoiceExcel } from '../../src/components/orders/invoiceExport';
import { appFixture } from './fixtures';

jest.mock('expo-print', () => ({ printToFileAsync: jest.fn() }));
jest.mock('expo-sharing', () => ({ isAvailableAsync: jest.fn(), shareAsync: jest.fn() }));
jest.mock('expo-file-system/legacy', () => ({ documentDirectory: 'file:///documents/', cacheDirectory: 'file:///cache/', writeAsStringAsync: jest.fn() }));
jest.mock('@redoper1/xlsx-js-style', () => ({ ...jest.requireActual('@redoper1/xlsx-js-style'), writeFile: jest.fn() }));
const previousOpen = globalThis.open;
let order, balance;
beforeEach(() => {
  ({ orders: [order], balances: [balance] } = appFixture());
  Print.printToFileAsync.mockResolvedValue({ uri: 'file:///unreadable/tmp.pdf', base64: 'JVBERi0=' });
  Sharing.isAvailableAsync.mockResolvedValue(true);
  Sharing.shareAsync.mockResolvedValue();
  FileSystem.writeAsStringAsync.mockResolvedValue();
});
afterEach(() => { jest.restoreAllMocks(); globalThis.open = previousOpen; });

test('native PDF copies generated bytes into readable app storage before sharing', async () => {
  await exportInvoicePdf(order, balance);
  expect(Print.printToFileAsync).toHaveBeenCalledWith(expect.objectContaining({ base64: true, html: expect.stringContaining('INV-001') }));
  expect(FileSystem.writeAsStringAsync).toHaveBeenCalledWith('file:///documents/invoice-INV-001.pdf', 'JVBERi0=', { encoding: 'base64' });
  expect(Sharing.shareAsync).toHaveBeenCalledWith('file:///documents/invoice-INV-001.pdf', expect.objectContaining({ mimeType: 'application/pdf' }));
});

test('PDF reports generation and sharing failures without claiming success', async () => {
  Print.printToFileAsync.mockResolvedValueOnce({});
  await expect(exportInvoicePdf(order, balance)).rejects.toThrow('Could not save');
  expect(Sharing.shareAsync).not.toHaveBeenCalled();
  Sharing.isAvailableAsync.mockResolvedValueOnce(false);
  await expect(exportInvoicePdf(order, balance)).rejects.toThrow('sharing is unavailable');
  Sharing.shareAsync.mockRejectedValueOnce(new Error('Permission denied'));
  await expect(exportInvoicePdf(order, balance)).rejects.toThrow('Permission denied');
});

test('native Excel writes a real styled workbook and shares an XLSX file', async () => {
  await exportInvoiceExcel(order, balance);
  const [uri, encoded, options] = FileSystem.writeAsStringAsync.mock.calls[0];
  expect(uri).toBe('file:///cache/invoice-INV-001.xlsx');
  expect(options).toEqual({ encoding: 'base64' });
  const workbook = XLSX.read(encoded, { type: 'base64', cellStyles: true });
  const sheet = workbook.Sheets[workbook.SheetNames[0]];
  expect(XLSX.utils.sheet_to_csv(sheet)).toContain('INV-001');
  expect(sheet['!merges'].length).toBeGreaterThan(0);
  expect(Sharing.shareAsync).toHaveBeenCalledWith(uri, expect.objectContaining({ mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }));
});

test('web exports use browser printing/download rather than native file sharing', async () => {
  jest.replaceProperty(Platform, 'OS', 'web');
  const popup = { document: { open: jest.fn(), write: jest.fn(), close: jest.fn() }, addEventListener: jest.fn(), focus: jest.fn(), print: jest.fn() };
  globalThis.open = jest.fn(() => popup);
  await exportInvoicePdf(order, balance);
  expect(popup.document.write).toHaveBeenCalledWith(expect.stringContaining('<table>'));
  popup.addEventListener.mock.calls[0][1]();
  expect(popup.print).toHaveBeenCalledTimes(1);
  expect(Print.printToFileAsync).not.toHaveBeenCalled();
  await exportInvoiceExcel(order, balance);
  expect(XLSX.writeFile).toHaveBeenCalledWith(expect.objectContaining({ Sheets: expect.any(Object) }), 'invoice-INV-001.xlsx', { bookType: 'xlsx' });
  expect(FileSystem.writeAsStringAsync).not.toHaveBeenCalled();
  expect(Sharing.shareAsync).not.toHaveBeenCalled();
});

test('export filenames cannot escape the app document directory', async () => {
  await exportInvoicePdf({ ...order, invoiceNumber: '../../unsafe/invoice' }, balance);
  expect(FileSystem.writeAsStringAsync.mock.calls[0][0]).toBe('file:///documents/invoice-------unsafe-invoice.pdf');
});

test('web PDF reports blocked popups instead of printing the application', async () => {
  jest.replaceProperty(Platform, 'OS', 'web');
  globalThis.open = jest.fn(() => null);
  await expect(exportInvoicePdf(order, balance)).rejects.toThrow('Allow pop-ups');
  expect(Print.printToFileAsync).not.toHaveBeenCalled();
});
